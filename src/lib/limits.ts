/**
 * 사용자가 쓰는 글의 길이 상한. 서버 액션과 화면이 같은 값을 본다.
 *
 * 예전에는 200이라는 숫자가 actions.ts의 LIMITS, saveEulogy의 인라인
 * 검사, CreateFlow의 maxLength 세 곳에 따로 적혀 있었다. 한 곳만 고치면
 * 화면은 받아주는데 서버가 거절하는 상태가 된다.
 *
 * DB 제약(각인 200자, 이름 24자)은 그대로 둔다. 여기 값은 제품이 약속하는
 * 길이이고, DB 제약은 그 약속이 깨졌을 때 데이터를 지키는 마지막 선이다.
 */

/**
 * 묘비에 새기는 문장.
 *
 * DB는 200자까지 허용하지만 200자는 문장이 아니라 문단이고, 묘비 안에
 * 넣으면 넘쳐서 버튼을 가린다. 공유 카드도 130자에서 자른다.
 * "추도문에서 한 문장을 고른다"는 이 제품의 동작에 맞는 길이로 줄였다.
 */
export const EPITAPH_MAX = 80;

/** 표시 이름. 묘비 위에 한 줄로 들어가야 한다. */
export const USER_NAME_MAX = 12;

/** 붙여넣는 LLM 답변 전문. */
export const EULOGY_MAX = 4000;
