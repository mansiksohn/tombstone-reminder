/**
 * LLM이 돌려준 글에서 마크다운 장식을 걷어낸다.
 *
 * 이 제품은 마크다운을 렌더하지 않는다. 사용자가 붙여넣은 글을 그대로
 * 보여주는 것이 원칙이고, 렌더러를 들이면 살균 처리까지 딸려온다
 * (구 코드의 dangerouslySetInnerHTML을 일부러 걷어낸 이력이 있다).
 *
 * 그런데 실제 LLM은 평문만 주지 않는다. 제목(##), 목록(-, 1.), 인용(>),
 * 강조(**)를 섞어 내놓는 편이 오히려 흔하다. 렌더하지 않으면 그 기호들이
 * 묘비와 추도문에 글자 그대로 박힌다.
 *
 * 그래서 저장은 원문 그대로 하고, 보여줄 때만 장식을 벗긴다. 되돌릴 수
 * 있는 선택이고, 나중에 렌더링으로 바꾸더라도 데이터는 멀쩡하다.
 */

/**
 * 후보에서 마크다운 장식을 걷어낸다.
 *
 * 실제 LLM은 평문만 주지 않는다. 제목(##), 목록(-, 1.), 인용(>), 강조(**)를
 * 섞어 내놓는 편이 오히려 흔하다. 그대로 두면 '> "잘 살았다"' 같은 후보가
 * 목록에 뜨고, 고르면 묘비에 꺾쇠와 별표가 새겨진다.
 *
 * 원문(추도문 전문)은 건드리지 않는다. 여기서 다듬는 것은 '한 문장을 고르는'
 * 목록에 보여줄 후보뿐이다.
 */
export function stripMarkdown(line: string): string {
  return line
    // 줄 앞의 인용·제목·목록 표시. 중첩될 수 있어 반복해서 벗긴다.
    .replace(/^(\s*(?:>+\s*|#{1,6}\s+|[-*+]\s+|\d+[.)]\s+))+/, '')
    // 굵게·기울임·취소선·인라인 코드
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/__(.+?)__/g, '$1')
    .replace(/~~(.+?)~~/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    // [보이는 글자](주소) → 보이는 글자
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    // 남은 홑별표 강조. 앞뒤에 공백을 요구하면 안 된다 — 한국어는 닫는
    // 별표 뒤에 조사가 바로 붙는다("*그것*이었습니다"). 대신 별표 안쪽이
    // 공백으로 시작·끝나지 않게 해서 곱셈 기호(3 * 4)는 건드리지 않는다.
    .replace(/\*(?!\s)([^*\n]+?)(?<!\s)\*/g, '$1')
    .trim();
}

/** 구분선 같은, 글이 아닌 줄. */
const RULE_ONLY = /^\s*([-*_])\s*(\1\s*){2,}$/;

/**
 * 여러 줄짜리 글 전체를 평문으로. 줄바꿈은 문단을 나누므로 보존한다.
 */
export function toPlainText(text: string): string {
  return text
    .split(/\r?\n/)
    .filter((line) => !RULE_ONLY.test(line))
    .map(stripMarkdown)
    .join('\n')
    // 구분선을 걷어낸 자리에 빈 줄이 겹쳐 남지 않도록.
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/** 한 줄이 글이 아닌 장식뿐인가 (구분선 등). */
export function isDecorationOnly(line: string): boolean {
  return RULE_ONLY.test(line);
}
